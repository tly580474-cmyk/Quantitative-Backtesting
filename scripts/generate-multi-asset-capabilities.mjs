import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const snapshotSource = await readFile(resolve(root, 'server/src/multiAsset/snapshotInput.ts'), 'utf8');
const extensionSource = await readFile(resolve(root, 'server/src/multiAsset/extensionSchema.ts'), 'utf8');
const outputPath = resolve(root, 'src/features/multiAsset/capabilities.generated.ts');

function stringLiterals(source, pattern, label) {
  const match = source.match(pattern);
  if (!match) throw new Error(`Unable to derive ${label} from source schemas`);
  return [...match[1].matchAll(/'([^']+)'/g)].map((item) => item[1]);
}

const indexCodes = stringLiterals(snapshotSource, /indexCode:\s*z\.enum\(\[([^\]]+)\]\)/, 'index universes');
const fundamentalFields = stringLiterals(snapshotSource, /fundamentalFields:\s*z\.array\(z\.enum\(\[([\s\S]*?)\]\)\)/, 'fundamental fields');
const optimizerModes = stringLiterals(extensionSource, /mode:\s*z\.enum\(\[([^\]]+)\]\)/, 'optimizer modes');
const capabilities = {
  protocolVersion: '1.0',
  universes: [...indexCodes.map((code) => `index:${code}`), 'all_a'],
  fundamentalFields,
  optimizerModes,
  pointInTimeFundamentals: extensionSource.includes('pointInTimeFundamentalEvidenceSchema'),
  industryNeutrality: extensionSource.includes('industryNeutralSpecSchema'),
  industryAbsoluteBounds: extensionSource.includes('absoluteBounds:'),
  extensionReport: extensionSource.includes('multiAssetExtensionReportSchema'),
};
const capabilityVersion = createHash('sha256').update(JSON.stringify(capabilities)).digest('hex');
const generated = `// Generated by scripts/generate-multi-asset-capabilities.mjs. Do not edit by hand.\n`
  + `export const MULTI_ASSET_CAPABILITIES = ${JSON.stringify({ ...capabilities, capabilityVersion }, null, 2)} as const;\n`;

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== generated) {
    console.error('Generated multi-asset capabilities are stale. Run npm run capabilities:generate.');
    process.exit(1);
  }
} else {
  await writeFile(outputPath, generated, 'utf8');
  console.log(`Generated multi-asset capabilities: ${outputPath}`);
}
